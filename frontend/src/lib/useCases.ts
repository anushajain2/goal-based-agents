export const USE_CASES: UseCase[] = CATEGORIES.flatMap((c) =>
  c.rows.map(([sub, goal, doneWhen, fit], i) => ({ id: `${c.key}-${i}`, category: c.name, categoryKey: c.key, sub, goal, doneWhen, fit })),
);

export const FIT_LABEL: Record<Fit, string> = { H: "Great fit", M: "Good fit", L: "Limited fit" };

export function findUseCase(id: string | null | undefined): UseCase | undefined {
  return id ? USE_CASES.find((u) => u.id === id) : undefined;
}

/** First number in the goal ("Book 20 meetings" -> 20, "2,000 contacts" -> 2000). */
export function targetFrom(goal: string): number | null {
  const m = goal.replace(/(\d),(\d{3})/g, "$1$2").match(/\d+(\.\d+)?/);
  return m ? Number(m[0]) : null;
}

/** What gets counted, from the finish line ("Meeting held on calendar, ..." -> "Meeting held on calendar"). */
export function metricFrom(doneWhen: string): string {
  return doneWhen.split(",")[0].trim().slice(0, 110);
}

